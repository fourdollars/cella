package trace

// SyscallName returns the name of a syscall by number (x86_64)
func SyscallName(nr int) string {
	if name, ok := syscallNames[nr]; ok {
		return name
	}
	return "unknown"
}

// SyscallFamilyOf categorizes a syscall by number (x86_64)
func SyscallFamilyOf(nr int) SyscallFamily {
	if family, ok := syscallFamilies[nr]; ok {
		return family
	}
	return FamilyOther
}

